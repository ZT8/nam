"""Embed the unmodified approved HTML and isolated native bridge in the dylib."""
from pathlib import Path
import hashlib
root=Path(__file__).resolve().parents[1]
rows=['// Generated by tools/embed_design.py. Do not edit.\n']
for name,file in [('HIDEApprovedHTML','HIDE_design.html'),('HIDENativeBridge','native-bridge.js')]:
    data=(root/'assets'/file).read_bytes()
    rows.append(f'// {file} SHA256 {hashlib.sha256(data).hexdigest()}\n')
    rows.append(f'static const unsigned char {name}[] = {{\n')
    rows.extend(','.join(str(b) for b in data[i:i+32])+',\n' for i in range(0,len(data),32))
    rows.append('};\n')
(root/'src/HIDEDesignData.h').write_text(''.join(rows))
